#!/usr/bin/env node
// Keeps the SDK's copy of the Flashpi API contract and the types generated from it in sync.
//
//   pnpm openapi:sync      download the public OpenAPI document, then regenerate the types
//   pnpm openapi:generate  regenerate src/generated/openapi.ts from the committed copy
//   pnpm openapi:check     fail when src/generated/openapi.ts is not what the copy generates (CI)
//
// The source is the public document the docs publish (https://flashpi.com.ec/docs/openapi.json),
// because the API repository is private. Override it with FLASHPI_OPENAPI_URL or point
// FLASHPI_OPENAPI_FILE at a local file (for example a flashpi-api checkout).
import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contractPath = path.join(root, 'openapi/openapi.json')
const typesPath = path.join(root, 'src/generated/openapi.ts')
const sourceUrl = process.env.FLASHPI_OPENAPI_URL ?? 'https://flashpi.com.ec/docs/openapi.json'
const sourceFile = process.env.FLASHPI_OPENAPI_FILE

const header = `/**
 * GENERATED by scripts/openapi.mjs from openapi/openapi.json, the public OpenAPI document of the
 * Flashpi API. Do not edit by hand: run \`pnpm openapi:sync\` (or \`pnpm openapi:generate\`).
 */
`

async function generate(contractJson) {
  const ast = await openapiTS(JSON.parse(contractJson), {
    alphabetize: true,
    exportType: true,
    rootTypes: true,
    rootTypesNoSchemaPrefix: true,
    // Properties with a default stay optional, so request bodies do not demand them.
    defaultNonNullable: false,
  })
  return header + astToString(ast)
}

async function download() {
  if (sourceFile) return readFile(sourceFile, 'utf8')
  const response = await fetch(sourceUrl, { headers: { accept: 'application/json' } })
  if (!response.ok) throw new Error(`GET ${sourceUrl} answered ${response.status}`)
  return response.text()
}

const mode = process.argv[2] ?? 'generate'
if (!['sync', 'generate', 'check'].includes(mode)) {
  console.error('Usage: node scripts/openapi.mjs sync|generate|check')
  process.exit(2)
}

if (mode === 'sync') {
  const contract = await download()
  const parsed = JSON.parse(contract) // fail early on a broken document
  if (typeof parsed.openapi !== 'string' || !parsed.paths) {
    throw new Error('The downloaded file is not an OpenAPI document')
  }
  await writeFile(contractPath, contract.endsWith('\n') ? contract : `${contract}\n`)
  console.log(`Copied ${sourceFile ?? sourceUrl} to openapi/openapi.json`)
}

const types = await generate(await readFile(contractPath, 'utf8'))

if (mode === 'check') {
  const current = existsSync(typesPath) ? await readFile(typesPath, 'utf8') : ''
  if (current !== types) {
    console.error('src/generated/openapi.ts is out of date. Run: pnpm openapi:generate')
    process.exit(1)
  }
  console.log('src/generated/openapi.ts matches openapi/openapi.json')
} else {
  await writeFile(typesPath, types)
  console.log('Wrote src/generated/openapi.ts')
}
